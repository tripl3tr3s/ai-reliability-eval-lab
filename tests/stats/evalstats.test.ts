import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { describe, expect, it } from "vitest";
import {
  bonettPriceClusterInterval,
  bonettPriceInterval,
  iccOneWay,
  mcnemarMidP,
  passAtKUnbiased,
  passPowerKUnbiased,
  pValueByInversion,
  shafferAdjust,
  sidakConfidence,
  STATS_REFERENCE,
  studentTQuantile,
  tInterval,
  wilsonInterval,
  wilsonOnCaseRates,
  type CaseTally,
} from "../../src/stats/index.js";

// Reference values come from evalstats itself, not from this code. Regenerate by hand with the command at the
// top of tests/stats/reference/evalstats_reference.py; the versions it ran with are recorded in the JSON.
const SCRIPT = "tests/stats/reference/evalstats_reference.py";
const fixtures = JSON.parse(await readFile("tests/stats/reference/evalstats-fixtures.json", "utf8")) as {
  scriptSha256: string;
  evalstatsVersion: string;
  wilson: { successes: number; trials: number; confidence: number; low: number; high: number }[];
  wilsonOnCaseRates: { rates: number[]; confidence: number; low: number; high: number }[];
  bonettPrice: { firstOnly: number; secondOnly: number; bothPassed: number; bothFailed: number; confidence: number; low: number; high: number; midP?: number; sidakComparisons?: number; familyConfidence?: number }[];
  mcnemarMidP: { firstOnly: number; secondOnly: number; midP: number }[];
  bonettPriceCluster: { first: number[][]; second: number[][]; confidence: number; low: number; high: number; pValue: number }[];
  shaffer: { groups: number; pValues: number[]; adjusted: number[] }[];
  reliability: { passes: number[]; trials: number | number[]; icc: number; designEffect: number; repeatsPerCase: number; passPowerK: Record<string, number>; passAtK: Record<string, number> }[];
  tInterval: {
    quantiles: { probability: number; df: number; quantile: number }[];
    intervals: { values: number[]; confidence: number; low: number; high: number }[];
  };
};

// normalQuantile is Acklam's approximation (relative error below 1.2e-9), so every value that goes through a
// normal quantile is compared to an absolute 1e-8. Exact binomial and combinatorial values are compared to 1e-12.
const Z_TOLERANCE = 1e-8;
const EXACT_TOLERANCE = 1e-12;
const near = (actual: number, expected: number, tolerance: number): void => {
  expect(Math.abs(actual - expected), `actual ${actual}, expected ${expected}`).toBeLessThanOrEqual(tolerance);
};
const rowMean = (row: readonly number[]): number => row.reduce((sum, value) => sum + value, 0) / row.length;

describe("evalstats reference fixtures", () => {
  it("were generated by the committed script, at the pinned evalstats version", async () => {
    const script = (await readFile(SCRIPT, "utf8")).replace(/\r\n/gu, "\n");
    expect(fixtures.scriptSha256).toBe(createHash("sha256").update(script, "utf8").digest("hex"));
    expect(fixtures.evalstatsVersion).toBe(STATS_REFERENCE.version);
    // Guards against a truncated or hand-edited fixture file making the loops below pass vacuously.
    expect(fixtures.wilson.length).toBeGreaterThanOrEqual(30);
    expect(fixtures.wilsonOnCaseRates.length).toBeGreaterThanOrEqual(5);
    expect(fixtures.bonettPrice.length).toBeGreaterThanOrEqual(25);
    expect(fixtures.mcnemarMidP.length).toBeGreaterThanOrEqual(10);
    expect(fixtures.bonettPriceCluster.length).toBeGreaterThanOrEqual(7);
    expect(fixtures.shaffer.length).toBeGreaterThanOrEqual(5);
    expect(fixtures.reliability.length).toBeGreaterThanOrEqual(6);
    expect(fixtures.reliability.some(({ trials }) => Array.isArray(trials))).toBe(true);
  });

  it("match evalstats wilson_ci", () => {
    for (const { successes, trials, confidence, low, high } of fixtures.wilson) {
      const interval = wilsonInterval(successes, trials, confidence);
      near(interval.low, low, Z_TOLERANCE);
      near(interval.high, high, Z_TOLERANCE);
    }
  });

  it("match evalstats wilson_ci_1d on per-case rates", () => {
    for (const { rates, confidence, low, high } of fixtures.wilsonOnCaseRates) {
      const interval = wilsonOnCaseRates(rates, confidence);
      near(interval.low, low, Z_TOLERANCE);
      near(interval.high, high, Z_TOLERANCE);
    }
  });

  it("match evalstats bonett_price_paired_ci, including a Sidak-widened interval", () => {
    for (const { firstOnly, secondOnly, bothPassed, bothFailed, confidence, low, high, sidakComparisons, familyConfidence } of fixtures.bonettPrice) {
      const level = sidakComparisons === undefined ? confidence : sidakConfidence(familyConfidence!, sidakComparisons);
      near(level, confidence, EXACT_TOLERANCE);
      const interval = bonettPriceInterval({ firstOnly, secondOnly, bothPassed, bothFailed }, level);
      near(interval.low, low, Z_TOLERANCE);
      near(interval.high, high, Z_TOLERANCE);
      expect(interval.estimate).toBe((firstOnly - secondOnly) / (firstOnly + secondOnly + bothPassed + bothFailed));
    }
  });

  it("match evalstats _mcnemar_midp_p", () => {
    for (const { firstOnly, secondOnly, midP } of [...fixtures.mcnemarMidP, ...fixtures.bonettPrice.filter((row) => row.midP !== undefined) as { firstOnly: number; secondOnly: number; midP: number }[]]) {
      near(mcnemarMidP({ firstOnly, secondOnly }), midP, EXACT_TOLERANCE);
    }
  });

  it("match evalstats bonett_price_paired_ci_multirun_cluster and its inverted p-value", () => {
    for (const { first, second, confidence, low, high, pValue } of fixtures.bonettPriceCluster) {
      const differences = first.map((row, index) => rowMean(row) - rowMean(second[index]!));
      const interval = bonettPriceClusterInterval(differences, confidence);
      near(interval.low, low, Z_TOLERANCE);
      near(interval.high, high, Z_TOLERANCE);
      near(pValueByInversion((alpha) => bonettPriceClusterInterval(differences, 1 - alpha)), pValue, 1e-7);
    }
  });

  it("match evalstats _shaffer_adjusted_pvalues for up to three groups", () => {
    // From four groups evalstats omits true-null counts such as 2 (see shafferTrueNullCounts), so only k <= 3 is compared.
    for (const { groups, pValues, adjusted } of fixtures.shaffer.filter(({ groups: count }) => count <= 3)) {
      shafferAdjust(pValues, groups).forEach((value, index) => near(value, adjusted[index]!, EXACT_TOLERANCE));
    }
  });

  it("match an independent numpy ICC(1) and math.comb pass^k and pass@k", () => {
    for (const { passes, trials, icc, designEffect, repeatsPerCase, passPowerK, passAtK } of fixtures.reliability) {
      const tallies: CaseTally[] = passes.map((count, index) => ({ caseId: `c${String(index).padStart(3, "0")}`, passes: count, trials: Array.isArray(trials) ? trials[index]! : trials }));
      const result = iccOneWay(tallies)!;
      near(result.icc, icc, EXACT_TOLERANCE);
      near(result.designEffect, designEffect, EXACT_TOLERANCE);
      near(result.repeatsPerCase, repeatsPerCase, EXACT_TOLERANCE);
      for (const [k, expected] of Object.entries(passPowerK)) near(passPowerKUnbiased(tallies, Number(k))!, expected, EXACT_TOLERANCE);
      for (const [k, expected] of Object.entries(passAtK)) near(passAtKUnbiased(tallies, Number(k))!, expected, EXACT_TOLERANCE);
    }
  });

  it("match scipy t.ppf and evalstats t_interval_ci_1d", () => {
    expect(fixtures.tInterval.quantiles.length).toBeGreaterThan(0);
    expect(fixtures.tInterval.intervals.length).toBeGreaterThan(0);
    // The t quantile is found by bisection on an incomplete-beta CDF, so it is compared to 1e-10 relative.
    for (const { probability, df, quantile } of fixtures.tInterval.quantiles) near(studentTQuantile(probability, df), quantile, 1e-10 * Math.max(1, Math.abs(quantile)));
    for (const { values, confidence, low, high } of fixtures.tInterval.intervals) {
      const interval = tInterval(values, confidence)!;
      near(interval.low, low, 1e-10);
      near(interval.high, high, 1e-10);
    }
  });
});
